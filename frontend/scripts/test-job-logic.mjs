import assert from "node:assert/strict";
import { normalizeSalaryParam, parseSalaryParam, localDateKey, isValidDateKey, isDateKeyBeforeToday, safeHttpUrl } from "../src/job-logic.js";
assert.equal(normalizeSalaryParam(null), "");
assert.equal(normalizeSalaryParam(""), "");
assert.equal(normalizeSalaryParam("  0012.50  "), "12.5");
assert.equal(normalizeSalaryParam("abc"), "");
assert.equal(normalizeSalaryParam("Infinity"), "");
assert.equal(normalizeSalaryParam("-1"), "");
assert.equal(parseSalaryParam("0"), 0);
assert.equal(parseSalaryParam("125.75"), 125.75);
assert.equal(parseSalaryParam("abc"), undefined);
assert.equal(parseSalaryParam("-0.01"), undefined);
assert.equal(parseSalaryParam("Infinity"), undefined);
assert.equal(localDateKey(new Date(2026, 9, 18)), "2026-10-18");
assert.equal(isValidDateKey("2024-02-29"), true);
assert.equal(isValidDateKey("2025-02-29"), false);
assert.equal(isValidDateKey("2026-13-01"), false);
assert.equal(isValidDateKey("18-10-2026"), false);
assert.equal(isDateKeyBeforeToday("2026-10-17", "2026-10-18"), true);
assert.equal(isDateKeyBeforeToday("2026-10-18", "2026-10-18"), false);
assert.equal(isDateKeyBeforeToday("2026-10-19", "2026-10-18"), false);
assert.equal(safeHttpUrl("https://example.com/jobs/1"), "https://example.com/jobs/1");
assert.equal(safeHttpUrl("http://example.com/job"), "http://example.com/job");
assert.equal(safeHttpUrl("javascript:alert(1)"), undefined);
assert.equal(safeHttpUrl("data:text/html,hi"), undefined);
assert.equal(safeHttpUrl("//example.com/path"), undefined);
assert.equal(safeHttpUrl("https://user:pass@example.com/path"), undefined);
assert.equal(safeHttpUrl("not a url"), undefined);
console.log("Job logic unit tests passed.");
